#!/usr/bin/env node
// Generates src/api/schema.gen.ts from gen/openapi/skein.swagger.json.
//
// The spec is OpenAPI 2.0 (Swagger), which openapi-typescript 7 no longer
// reads, and the subset grpc-gateway emits is small and regular, so this
// generator is a page of code with no dependencies:
//   - every definition becomes an interface (all fields optional, because
//     proto3 JSON omits defaults) or a string union for enums;
//   - every operation becomes an entry in `operations` (method, path, which
//     parameters go in the path and query) and in the `Operations` type map
//     (params, body, response), which src/api/client.ts uses to type calls.
// Types follow the spec's JSON types: 64-bit integers are strings there,
// because proto3 JSON writes them as strings.
//
// Usage: node scripts/gen-api.mjs [--check]
//   --check  exit 1 when the committed file differs from what would be generated.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const specPath = resolve(here, "../../gen/openapi/skein.swagger.json");
const outPath = resolve(here, "../src/api/schema.gen.ts");
const spec = JSON.parse(readFileSync(specPath, "utf8"));

const refName = (ref) => ref.replace("#/definitions/", "");
const ident = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));
const doc = (text, indent = "") =>
  text ? `${indent}/** ${text.replace(/\*\//g, "*\\/").split("\n").join(`\n${indent} * `)} */\n` : "";

function typeOf(schema) {
  if (!schema) return "unknown";
  if (schema.$ref) return refName(schema.$ref);
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `${wrap(typeOf(schema.items))}[]`;
    case "object":
      if (schema.additionalProperties) return `Record<string, ${typeOf(schema.additionalProperties)}>`;
      if (schema.properties) return inlineObject(schema);
      return "Record<string, unknown>";
    default:
      return "unknown";
  }
}

const wrap = (t) => (t.includes("|") ? `(${t})` : t);

function inlineObject(schema) {
  const fields = Object.entries(schema.properties ?? {}).map(([k, v]) => `${ident(k)}?: ${typeOf(v)}`);
  return `{ ${fields.join("; ")} }`;
}

const out = [];
out.push(
  "// Code generated by scripts/gen-api.mjs from gen/openapi/skein.swagger.json. DO NOT EDIT.",
  "// Regenerate with `pnpm gen:api` after `make proto`.",
  "/* eslint-disable */",
  "",
);

for (const name of Object.keys(spec.definitions).sort()) {
  const def = spec.definitions[name];
  if (def.enum) {
    out.push(`${doc(def.description)}export type ${name} = ${def.enum.map((v) => JSON.stringify(v)).join(" | ")};`, "");
    continue;
  }
  out.push(`${doc(def.description)}export interface ${name} {`);
  for (const [field, schema] of Object.entries(def.properties ?? {})) {
    out.push(`${doc(schema.description ?? schema.title, "  ")}  ${ident(field)}?: ${typeOf(schema)};`);
  }
  out.push("}", "");
}

const operations = [];
for (const [path, methods] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(methods)) {
    const params = op.parameters ?? [];
    const pathParams = params.filter((p) => p.in === "path");
    const queryParams = params.filter((p) => p.in === "query");
    const body = params.find((p) => p.in === "body");
    operations.push({
      id: op.operationId,
      method: method.toUpperCase(),
      path,
      summary: op.summary,
      pathParams,
      queryParams,
      body: body ? typeOf(body.schema) : null,
      response: typeOf(op.responses?.["200"]?.schema),
    });
  }
}
operations.sort((a, b) => a.id.localeCompare(b.id));

out.push("/** Path and query parameters of each operation; query names keep their dots (page.pageSize). */");
for (const op of operations) {
  const fields = [
    ...op.pathParams.map((p) => `  ${ident(p.name)}: string;`),
    ...op.queryParams.map((p) => {
      const t = p.type === "array" ? `${wrap(typeOf(p.items))}[]` : p.enum ? typeOf(p) : typeOf({ type: p.type });
      return `${doc(p.description, "  ")}  ${ident(p.name)}${p.required ? "" : "?"}: ${t};`;
    }),
  ];
  out.push(`export interface ${op.id}_Params {`, ...fields, "}", "");
}

out.push("/** Every REST operation in the spec, keyed by operationId. */", "export interface Operations {");
for (const op of operations) {
  out.push(
    `${doc(op.summary, "  ")}  ${op.id}: { params: ${op.id}_Params; body: ${op.body ?? "undefined"}; response: ${op.response} };`,
  );
}
out.push("}", "");

out.push(
  "/** How each operation maps to HTTP: method, path template, and which parameters go in the path and query. */",
  "export const operations = {",
);
for (const op of operations) {
  out.push(
    `  ${op.id}: { method: ${JSON.stringify(op.method)}, path: ${JSON.stringify(op.path)}, pathParams: ${JSON.stringify(
      op.pathParams.map((p) => p.name),
    )}, queryParams: ${JSON.stringify(op.queryParams.map((p) => p.name))}, hasBody: ${op.body !== null} },`,
  );
}
out.push("} as const;", "", "export type OperationId = keyof Operations;", "");

const generated = out.join("\n");
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    // missing counts as stale
  }
  if (current !== generated) {
    console.error("src/api/schema.gen.ts is stale: run `pnpm gen:api` and commit the result");
    process.exit(1);
  }
  console.log("src/api/schema.gen.ts is up to date");
} else {
  writeFileSync(outPath, generated);
  console.log(`wrote ${operations.length} operations and ${Object.keys(spec.definitions).length} definitions to src/api/schema.gen.ts`);
}
