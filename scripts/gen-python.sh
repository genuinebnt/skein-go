#!/usr/bin/env sh
# Generates the Python package skein_proto (gen/python/skein_proto) from
# proto/skein/v1 with grpcio-tools: messages (_pb2), type stubs (_pb2.pyi)
# and gRPC stubs (_pb2_grpc). Run from anywhere; `make proto` calls it.
#
# Layout and why:
#   skein_proto/v1/                     skein/v1/*.proto
#   skein_proto/protoc_gen_openapiv2/   the vendored openapiv2 options, which
#                                       our protos import and which have no
#                                       maintained PyPI package
# google/api/* is not generated: it comes from googleapis-common-protos.
#
# protoc's Python generator writes absolute imports that mirror the proto
# path ("from skein.v1 import common_pb2"). Python has no option to prefix
# them, so they are rewritten to live under skein_proto. That keeps the
# import name unique ("skein" alone would collide too easily) while the proto
# file names registered in the descriptor pool stay the canonical ones.
#
# The output must be reproducible: CI regenerates it and fails on any diff,
# so the grpcio-tools version is pinned (GRPCIO_TOOLS_VERSION below, also in
# the Makefile and CI).
set -eu

GRPCIO_TOOLS_VERSION=1.85.1

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/gen/python/skein_proto"
python=${PYTHON:-python3}

installed=$("$python" -c 'import importlib.metadata as m; print(m.version("grpcio-tools"))' 2>/dev/null || echo none)
if [ "$installed" != "$GRPCIO_TOOLS_VERSION" ]; then
  echo "gen-python: need grpcio-tools==$GRPCIO_TOOLS_VERSION, found $installed" >&2
  echo "  pip install grpcio-tools==$GRPCIO_TOOLS_VERSION" >&2
  exit 1
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

cd "$root/proto"
# third_party comes first so its files resolve to their canonical names
# (google/api/..., protoc-gen-openapiv2/...) rather than third_party/....
"$python" -m grpc_tools.protoc -Ithird_party -I. \
  --python_out="$tmp" --pyi_out="$tmp" --grpc_python_out="$tmp" \
  skein/v1/*.proto
"$python" -m grpc_tools.protoc -Ithird_party -I. \
  --python_out="$tmp" --pyi_out="$tmp" \
  third_party/protoc-gen-openapiv2/options/*.proto

rm -rf "$out/v1" "$out/protoc_gen_openapiv2"
mkdir -p "$out"
mv "$tmp/skein/v1" "$out/v1"
mv "$tmp/protoc_gen_openapiv2" "$out/protoc_gen_openapiv2"

find "$out/v1" "$out/protoc_gen_openapiv2" -name '*.py' -o -name '*.pyi' | sort | while read -r f; do
  sed -e 's/^from skein\.v1 import /from skein_proto.v1 import /' \
      -e 's/^from protoc_gen_openapiv2\.options import /from skein_proto.protoc_gen_openapiv2.options import /' \
      "$f" > "$f.tmp"
  mv "$f.tmp" "$f"
done

for d in "$out/v1" "$out/protoc_gen_openapiv2" "$out/protoc_gen_openapiv2/options"; do
  echo '"""Generated by scripts/gen-python.sh. Do not edit."""' > "$d/__init__.py"
done

echo "gen-python: wrote $(find "$out" -name '*.py' | wc -l | tr -d ' ') modules to gen/python/skein_proto"
